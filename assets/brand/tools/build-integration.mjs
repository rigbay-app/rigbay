// Copies exactly what the app needs into assets/brand/integration/ (the integration itself is a separate task: src/* is not touched here).
// Run after build-raster.mjs: node assets/brand/tools/build-integration.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, modules } from './build-svgs.mjs';
import { dock } from './lib/marks.mjs';

const dest = path.join(ROOT, 'integration');
for (const d of ['Assets', 'xaml', 'svg', 'module-icons', 'host-defaults']) fs.rmSync(path.join(dest, d), { recursive: true, force: true }); // the README stays
const cp = (from, to) => { const f = path.join(dest, to); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.copyFileSync(path.join(ROOT, from), f); };

// 1. app icon (exe, taskbar, Start, window) and tray icons
cp('app-icon/rigbay.ico', 'Assets/rigbay.ico');
for (const v of ['light', 'dark', 'neutral']) cp(`app-icon/tray/rigbay-tray-${v}.ico`, `Assets/rigbay-tray-${v}.ico`);
for (const v of ['black', 'white']) cp(`app-icon/high-contrast/rigbay-hc-${v}.ico`, `Assets/rigbay-hc-${v}.ico`);

// 2. title bar mark: path data for XAML (follows the Windows accent). Full drawing at 24 DIP and above, small cut below.
const xaml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/brand/tools/build-integration.mjs. Path data of the Rigbay Dock mark on a 208 x 208 canvas.
     Not compiled in this task (src/* is out of scope): the integration task should confirm WinUI accepts it as written. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <x:String x:Key="RbMarkBay">${dock.full.bay}</x:String>
  <x:String x:Key="RbMarkBlock">${dock.full.block}</x:String>
  <x:String x:Key="RbMarkBaySmall">${dock.small.bay}</x:String>
  <x:String x:Key="RbMarkBlockSmall">${dock.small.block}</x:String>
</ResourceDictionary>
`;
fs.mkdirSync(path.join(dest, 'xaml'), { recursive: true });
fs.writeFileSync(path.join(dest, 'xaml', 'RigbayMark.xaml'), xaml);
cp('rigbay/rigbay-symbol-small.svg', 'svg/rigbay-symbol-small.svg');
cp('rigbay/rigbay-symbol.svg', 'svg/rigbay-symbol.svg');
cp('rigbay/rigbay-symbol-accent.svg', 'svg/rigbay-symbol-accent.svg');

// 3. module icons: one folder per built-in module, named as a module author names them in the module folder
for (const m of modules.filter((m) => !['module-unknown', 'module-template'].includes(m.id))) {
  const d = `module-icons/${m.id}`;
  cp(`modules/${m.id}.svg`, `${d}/icon.svg`);
  cp(`modules/${m.id}-glyph.svg`, `${d}/icon-glyph.svg`);
  for (const s of [16, 24, 32, 48, 64, 128]) cp(`modules/png/${m.id}-${s}.png`, `${d}/icon-${s}.png`);
}
// 4. host defaults: the "?" tile for a module without an icon, and the template's tile
for (const id of ['module-unknown', 'module-template']) {
  const d = `host-defaults/${id}`;
  cp(`modules/${id}.svg`, `${d}/icon.svg`); cp(`modules/${id}-glyph.svg`, `${d}/icon-glyph.svg`); cp(`modules/${id}-unsupported.svg`, `${d}/icon-unsupported.svg`);
  for (const s of [16, 24, 32, 48, 64, 128]) cp(`modules/png/${id}-${s}.png`, `${d}/icon-${s}.png`);
}
// 5. the unsupported variants of the built-in modules (host-side: shown when a module's Probe says unsupported)
for (const m of modules.filter((m) => !['module-unknown', 'module-template'].includes(m.id))) {
  cp(`modules/${m.id}-unsupported.svg`, `module-icons/${m.id}/icon-unsupported.svg`);
  for (const s of [16, 24, 32, 48]) cp(`modules/png/${m.id}-unsupported-${s}.png`, `module-icons/${m.id}/icon-unsupported-${s}.png`);
}
let n = 0; const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : n++));
walk(dest);
console.log(`integration/: ${n} files`);
